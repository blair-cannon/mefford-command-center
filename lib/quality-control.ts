export const SCHEDULE_QUALITY_CATEGORIES: ScheduleQualityCategory[] = [
  ...PREWORK_QUALITY_TEMPLATES.map((template) => ({
    id: template.id,
    label: template.shortTitle,
    templateId: template.id,
    leadDays: template.id === "crane" ? 7 : template.id === "trenching-excavation" ? 5 : 3,
  })),
  { id: "general-administrative", label: "General / Administrative", templateId: "", leadDays: 0 },
  { id: "closeout-commissioning", label: "Closeout / Commissioning", templateId: "", leadDays: 0 },
];

export function scheduleQualityCategory(id: string) {
  return SCHEDULE_QUALITY_CATEGORIES.find((category) => category.id === id) || null;
}

export function qualityChecklistDueDate(activityStart: string, categoryId: string) {
  const category = scheduleQualityCategory(categoryId);
  if (!category?.templateId || !/^\d{4}-\d{2}-\d{2}$/.test(activityStart)) return "";
  const due = new Date(`${activityStart}T12:00:00Z`);
  due.setUTCDate(due.getUTCDate() - category.leadDays);
  return due.toISOString().slice(0, 10);
}

export type QualityResponse = { questionId: string; answer: string; note: string };

export function templateById(id: string) {
  return PREWORK_QUALITY_TEMPLATES.find((template) => template.id === id) || null;
}

export function inspectionResult(template: QualityTemplate, responses: QualityResponse[]) {
  const responseMap = new Map(responses.map((response) => [response.questionId, response]));
  const incomplete = template.questions.filter((question) => !responseMap.get(question.id)?.answer.trim());
  const failed = template.questions.filter((question) => question.input === "check" && responseMap.get(question.id)?.answer === "No");
  const unjustifiedNa = template.questions.filter((question) => question.input === "check" && responseMap.get(question.id)?.answer === "N/A" && !responseMap.get(question.id)?.note.trim());
  return { complete: incomplete.length === 0 && unjustifiedNa.length === 0, incomplete, failed, unjustifiedNa, satisfactory: incomplete.length === 0 && unjustifiedNa.length === 0 && failed.length === 0 };
}

export function parseQualityData(value: string): Record<string, unknown> {
  try {
    const parsed = JSON.parse(value) as unknown;
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed as Record<string, unknown> : {};
  } catch {
    return {};
  }
}

export function normalizeStringArray(value: unknown) {
  return Array.isArray(value) ? value.map(String).filter(Boolean) : [];
}
