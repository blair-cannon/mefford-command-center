export const QUALITY_INSPECTION_RECORD_TYPE = "Quality Inspections";
export const QUALITY_ITEM_RECORD_TYPE = "Quality Items";

export type QualityQuestion = {
  id: string;
  group: string;
  label: string;
  input: "check" | "text" | "choice";
  choices?: string[];
  required: boolean;
};

export type QualityTemplate = {
  id: string;
  title: string;
  shortTitle: string;
  sourceDocument: string;
  timing: string;
  questions: QualityQuestion[];
};

export type ScheduleQualityCategory = {
  id: string;
  label: string;
  templateId: string;
  leadDays: number;
};

const check = (id: string, group: string, label: string): QualityQuestion => ({ id, group, label, input: "check", required: true });
const text = (id: string, group: string, label: string): QualityQuestion => ({ id, group, label, input: "text", required: true });
const choice = (id: string, group: string, label: string, choices: string[]): QualityQuestion => ({ id, group, label, input: "choice", choices, required: true });

const standard = (prefix: string): QualityQuestion[] => [
  check(`${prefix}-site-safety`, "Planning & Safety", "Site coordination and safety concerns have been addressed."),
  check(`${prefix}-submittals`, "Planning & Safety", "Required submittals are complete, approved, and returned."),
  check(`${prefix}-delivery`, "Logistics", "Material delivery dates and off-loading responsibilities are established."),
  check(`${prefix}-storage`, "Logistics", "Material staging, storage, and protection are established."),
  check(`${prefix}-coordination`, "Coordination", "Coordination with affected trades and activities is complete."),
  check(`${prefix}-scope`, "Coordination", "The subcontractor's complete scope of work is defined."),
];

const closeout = (prefix: string): QualityQuestion[] => [
  check(`${prefix}-nonroutine`, "Completion", "Non-routine tasks and special conditions have been identified."),
  check(`${prefix}-testing`, "Completion", "Required inspections and testing have been identified and scheduled."),
  check(`${prefix}-cleanup`, "Completion", "Cleanup and protection responsibilities are established."),
];

